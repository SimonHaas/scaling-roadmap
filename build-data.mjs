// Merges the verified roadmap transcripts, placement questions and step data
// into one typed module the app imports. Run: node build-data.mjs
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve('..', 'roadmap');
const read = (p) => JSON.parse(fs.readFileSync(path.join(ROOT, p), 'utf8'));

const stages = read('stages.json');
const questions = read('questions.json');

const merged = {};
for (const key of Object.keys(stages).sort()) {
  const s = stages[key];
  const stepFile = path.join(ROOT, 'steps', `stage-${key}.json`);
  if (!fs.existsSync(stepFile)) throw new Error(`missing step data for stage ${key}`);
  const st = JSON.parse(fs.readFileSync(stepFile, 'utf8'));

  if (!Array.isArray(st.steps) || st.steps.length !== 8) {
    throw new Error(`stage ${key} has ${st.steps?.length} steps, expected 8`);
  }
  for (const step of st.steps) {
    if (!step.id || !step.evidencePrompt || !Array.isArray(step.doneWhen) || !step.doneWhen.length) {
      throw new Error(`stage ${key} step ${step.id} is incomplete`);
    }
  }

  merged[key] = {
    n: s.n,
    key,
    name: s.name,
    snapshot: s.snapshot,
    bottom: s.bottom,
    rows: s.rows,
    steps: st.steps
      .slice()
      .sort((a, b) => (a.order ?? 0) - (b.order ?? 0))
      .map((x, i) => ({ ...x, order: i })),
    graduation: st.graduation,
  };
}

const banner = `// GENERATED by build-data.mjs from ../roadmap. Do not edit by hand.
// Source: the ten official Acquisition.com $100M Scaling Roadmap stage guides.
`;

const ts =
  banner +
  `export type Step = {
  id: string; function: string; title: string; theProblem: string;
  whatToDo: string; doneWhen: string[]; evidencePrompt: string; order: number;
};
export type Stage = {
  n: number; key: string; name: string;
  snapshot: { headcount: string; role: string; structure: string; companies: string };
  bottom: { constraint: string; graduate: string };
  rows: { function: string; constraint: string; graduate: string }[];
  steps: Step[];
  graduation: { bottomLine: string; theOneThing: string; criteria: string[] };
};
export type QuestionOption = { label: string; stage: number; note: string };
export type Question = { id: string; q: string; kind: 'structural' | 'working'; opts: QuestionOption[] };

export const STAGES: Record<string, Stage> = ${JSON.stringify(merged, null, 1)} as const;
export const QUESTIONS: Question[] = ${JSON.stringify(questions, null, 1)} as const;
export const STAGE_KEYS = Object.keys(STAGES).sort();
export const stageOf = (n: number): Stage => STAGES[String(n).padStart(2, '0')];
`;

fs.mkdirSync('src/data', { recursive: true });
fs.writeFileSync('src/data/roadmap.ts', ts, 'utf8');
// checked by scripts/check-questions.mjs at build time; must live inside the
// project root because Vercel only uploads this directory
fs.writeFileSync('src/data/questions.json', JSON.stringify(questions, null, 1), 'utf8');

const stepCount = Object.values(merged).reduce((a, s) => a + s.steps.length, 0);
const checkCount = Object.values(merged).reduce(
  (a, s) => a + s.steps.reduce((b, x) => b + x.doneWhen.length, 0), 0);
console.log(`wrote src/data/roadmap.ts — ${Object.keys(merged).length} stages, ${stepCount} steps, ${checkCount} checks, ${questions.length} placement questions`);
